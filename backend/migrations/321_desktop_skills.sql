-- HiveGPT 桌面助手技能库 (docs/DESKTOP_ASSISTANT_PHASE2_PLAN.md, 二期 B). Each published row is sent to
-- the app by GET /api/v1/desktop/skills: a card in the empty chat (icon, title, summary, prepare, prompt,
-- sample_prompt) and a Codex skill (SKILL.md = name hivegpt-<slug> + summary + instructions) that the
-- app writes into its private CODEX_HOME, so Codex also uses it when the user just describes the task.
-- version goes up on every save; the app re-downloads a skill only when it changes.
CREATE TABLE IF NOT EXISTS desktop_skills (
    id             BIGSERIAL    PRIMARY KEY,
    slug           VARCHAR(48)  NOT NULL UNIQUE,
    title          VARCHAR(40)  NOT NULL,
    icon           VARCHAR(16)  NOT NULL DEFAULT '',
    summary        VARCHAR(200) NOT NULL DEFAULT '',
    prepare        TEXT         NOT NULL DEFAULT '',
    prompt         TEXT         NOT NULL DEFAULT '',
    sample_prompt  TEXT         NOT NULL DEFAULT '',
    instructions   TEXT         NOT NULL DEFAULT '',
    needs_office   BOOLEAN      NOT NULL DEFAULT TRUE,
    status         VARCHAR(16)  NOT NULL DEFAULT 'draft',
    sort_order     INTEGER      NOT NULL DEFAULT 0,
    version        INTEGER      NOT NULL DEFAULT 1,
    created_by     BIGINT,
    updated_by     BIGINT,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_desktop_skills_status_sort ON desktop_skills (status, sort_order, id);

