def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    corpus, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    names = [c[0] for c in CANDIDATES]
    if len(names) != len(set(names)):
        sys.exit("duplicate candidate names")
    clashes = sorted({a for _, _, al in CANDIDATES for a in al if a in names})
    if clashes:
        sys.exit(f"aliases that are also candidate names: {clashes}")
    counts = {n: 0 for n in names}
    dynasties: dict[str, int] = {}
    total = 0
    files = sorted(corpus.glob("volume_*.json"))
    for f in files:
        for poem in json.loads(f.read_text(encoding="utf-8")):
            text = (poem.get("title") or "") + "\n" + (poem.get("content") or "")
            total += 1
            d = poem.get("dynasty") or "未知"
            dynasties[d] = dynasties.get(d, 0) + 1
            for name, _, aliases in CANDIDATES:
                if name in text or any(len(a) > 1 and a in text for a in aliases):
                    counts[name] += 1
    if total == 0:
        sys.exit(f"no poems found under {corpus}")
    ranked = sorted(CANDIDATES, key=lambda c: (-counts[c[0]], c[0]))
    items = [{"rank": i + 1, "name": n, "category": cat, "aliases": al, "poems": counts[n]}
             for i, (n, cat, al) in enumerate(ranked)]
    out.write_text(json.dumps({
        "source": "open-chinese/poetry-collection (MIT), volumes/*.json",
        "files": f"{len(files)} ({files[0].name} … {files[-1].name})",
        "poems": total,
        "dynasties": dict(sorted(dynasties.items(), key=lambda kv: -kv[1])),
        "note": "A candidate counts once per poem containing its name or a 2+ character alias. Used to pick seed order only.",
        "items": items,
    }, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{total} poems, {len(items)} candidates → {out}")
    for it in items[:20]:
        print(f'{it["rank"]:>3} {it["name"]:<6} {it["category"]:<5} {it["poems"]}')


if __name__ == "__main__":
    main()
